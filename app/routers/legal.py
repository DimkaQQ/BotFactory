"""Оферта и политика конфиденциальности.

Сервис берёт деньги, значит у человека должно быть чёрным по белому
написано: с кем он договаривается, за что платит, как вернуть деньги и куда
писать, если что-то пошло не так. До этого на сайте не было ни одного из
четырёх ответов — ни контакта поддержки, ни названия того, кто получает
оплату. Первый же спор по платежу упирался бы ровно в это.

Документы собираются из реквизитов в настройках, а не лежат текстом в
репозитории: цифры в них должны совпадать с теми, по которым сервис на
самом деле выставляет счёт, а название — с тем, кто эти деньги получает.
Пока реквизиты не заполнены, обе страницы отдают 404, и ссылки на них на
сайте не показываются: оферта, подписанная никем, хуже отсутствующей.

Текст — шаблон. Его должен прочитать юрист той юрисдикции, в которой
зарегистрировано юрлицо, до того как сервис начнёт продавать.
"""

from __future__ import annotations

import html

from fastapi import APIRouter, HTTPException, Response, status

from app.config import get_settings

router = APIRouter(prefix="/legal", tags=["legal"])

#: Дата редакции текстов. Именно константа, а не «сегодня»: документ, у
#: которого дата меняется каждый день, нельзя датировать для спора. Поменяй
#: её, когда меняешь текст, — и только тогда.
REVISION = "02.10.2026"

#: Какие документы есть и как называются. Порядок — порядок в подвале.
DOCUMENTS: list[tuple[str, str]] = [
    ("offer", "Публичная оферта"),
    ("privacy", "Политика конфиденциальности"),
    ("refunds", "Условия возврата"),
    ("acceptable-use", "Правила допустимого использования"),
    ("data-processing", "Обработка данных покупателей"),
    ("cookies", "Cookies и локальное хранилище"),
]


#: Те же документы по-английски: проверяющий Stripe и эстонский регулятор
#: русского не читают. Тексты — в legal_en.py, адреса те же, язык — `?lang=en`.
TITLES_EN = {
    "offer": "Public Offer (Terms of Service)",
    "privacy": "Privacy Policy",
    "refunds": "Refund Policy",
    "acceptable-use": "Acceptable Use Policy",
    "data-processing": "Data Processing Terms for Bot Owners",
    "cookies": "Cookies and Local Storage",
}
_RU_TITLES = {title: slug for slug, title in DOCUMENTS}


def _lang(value: str) -> str:
    return "en" if value == "en" else "ru"


def document_links() -> list[dict[str, str]]:
    """Что показать в подвале: пусто, пока документам некому подписаться."""
    if not get_settings().legal_ready:
        return []
    return [{"path": f"/legal/{slug}", "title": title} for slug, title in DOCUMENTS]


def _prices() -> tuple[str, str]:
    """Что написать в оферте про деньги: запуск и период.

    Берём из тех же настроек, по которым выставляется счёт, — расхождение
    между ценой в оферте и ценой на кнопке это уже не опечатка.
    """
    from app.services import payment_service
    from app.services.payments import money

    methods = payment_service.platform_methods()
    if not methods:
        return ("Стоимость запуска указывается на кнопке публикации.", "")

    launch = ", ".join(sorted({money(m.price_minor, m.currency) for m in methods}))
    periodic = sorted({money(m.renewal_price_minor, m.currency) for m in methods if m.renewal_price_minor > 0})
    days = get_settings().renewal_period_days
    return (
        f"Запуск одного бота — {launch} (единоразово).",
        f"Работа запущенного бота — {', '.join(periodic)} за {days} дней." if periodic else "",
    )


def _page(title: str, body: str, lang: str = "ru") -> Response:
    """Один документ. Без сборки фронтенда: эти страницы должны открываться
    у юриста, у эквайера и у поддержки Telegram — то есть всегда, даже если
    приложение не поднялось."""
    settings = get_settings()
    en = lang == "en"
    slug = _RU_TITLES.get(title) or next((s for s, t in TITLES_EN.items() if t == title), "")
    path = f"/legal/{slug}" if slug else "/legal/"
    switch = (
        f'<a href="{path}">Русский</a> · <strong>English</strong>'
        if en
        else f'<strong>Русский</strong> · <a href="{path}?lang=en">English</a>'
    )
    support = settings.support_contact
    contacts = [f'<a href="https://t.me/{html.escape(support)}">@{html.escape(support)}</a>'] if support else []
    if settings.support_email:
        email = html.escape(settings.support_email)
        contacts.append(f'<a href="mailto:{email}">{email}</a>')

    return Response(
        content=f"""<!doctype html>
<html lang="{"en" if en else "ru"}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(title)}</title>
<style>
  :root {{ color-scheme: light dark; }}
  body {{
    margin: 0 auto; padding: 32px 20px 80px; max-width: 760px;
    font: 16px/1.65 -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
  }}
  h1 {{ font-size: 25px; line-height: 1.25; }}
  h2 {{ margin-top: 34px; font-size: 18px; }}
  li {{ margin-bottom: 6px; }}
  .meta {{ opacity: 0.65; font-size: 14px; }}
  .req {{ margin-top: 40px; padding: 16px; border-radius: 10px; background: rgba(127,127,127,0.12); font-size: 14px; }}
  a {{ color: inherit; }}
</style>
</head>
<body>
<h1>{html.escape(title)}</h1>
<p class="meta">{("Revision of " if en else "Редакция от ")}{REVISION} · <a href="/legal/{"?lang=en" if en else ""}">{"all documents" if en else "все документы"}</a> · {switch}</p>
{body}
<div class="req">
  <p><strong>{html.escape(settings.legal_name)}</strong><br>
  {html.escape(settings.legal_id)}{"<br>" + html.escape(settings.legal_address) if settings.legal_address else ""}{("<br>VAT: " if en else "<br>НДС (VAT): ") + html.escape(settings.legal_vat) if settings.legal_vat else ""}</p>
  {_agent_block(settings, en)}
  <p>{"Contact" if en else "Связаться"}: {" · ".join(contacts) if contacts else "—"}</p>
</div>
</body>
</html>
""",
        media_type="text/html; charset=utf-8",
    )


def _agent_block(settings, en: bool = False) -> str:
    """Реквизиты платёжного агента внизу страницы — если он назначен."""
    if not settings.agent_ready:
        return ""
    address = "<br>" + html.escape(settings.agent_address) if settings.agent_address else ""
    label = (
        "Payment agent (collects payments on behalf of the Provider):"
        if en
        else "Платёжный агент (принимает оплату от имени Исполнителя):"
    )
    return (
        f"<p>{label}<br>"
        f"<strong>{html.escape(settings.agent_name)}</strong><br>{html.escape(settings.agent_id)}{address}</p>"
    )


def _agent_clause(settings, *, what: str) -> str:
    """Один и тот же абзац про агента во всех документах, где он уместен."""
    if not settings.agent_ready:
        return ""
    return (
        f"<li>{what} осуществляет платёжный агент {html.escape(settings.agent_name)} "
        f"({html.escape(settings.agent_id)}) от имени и по поручению Исполнителя. Агент не является "
        "стороной договора: обязательства перед Пользователем несёт Исполнитель.</li>"
    )


def _require_requisites() -> None:
    if not get_settings().legal_ready:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Not found")


