"""Оферта и политика конфиденциальности.

Сервис берёт деньги, значит у человека должно быть чёрным по белому
написано: с кем он договаривается, за что платит, как вернуть деньги и куда
писать, если что-то пошло не так. До этого на сайте не было ни одного из
четырёх ответов — ни контакта поддержки, ни названия того, кто получает
оплату. Первый же спор по платежу упирался бы ровно в это.

Документы собираются из реквизитов в настройках, а не лежат текстом в
репозитории: цифры в них должны совпадать с теми, по которым сервис на
самом деле выставляет счёт, а название — с тем, кто эти деньги получает.
Пока реквизиты не заполнены, обе страницы отдают 404, и ссылки на них на
сайте не показываются: оферта, подписанная никем, хуже отсутствующей.

Текст — шаблон. Его должен прочитать юрист той юрисдикции, в которой
зарегистрировано юрлицо, до того как сервис начнёт продавать.
"""

from __future__ import annotations

import html
from datetime import date

from fastapi import APIRouter, HTTPException, Response, status

from app.config import get_settings

router = APIRouter(prefix="/legal", tags=["legal"])


def _prices() -> tuple[str, str]:
    """Что написать в оферте про деньги: запуск и период.

    Берём из тех же настроек, по которым выставляется счёт, — расхождение
    между ценой в оферте и ценой на кнопке это уже не опечатка.
    """
    from app.services import payment_service
    from app.services.payments import money

    methods = payment_service.platform_methods()
    if not methods:
        return ("Стоимость запуска указывается на кнопке публикации.", "")

    launch = ", ".join(sorted({money(m.price_minor, m.currency) for m in methods}))
    periodic = sorted({money(m.renewal_price_minor, m.currency) for m in methods if m.renewal_price_minor > 0})
    days = get_settings().renewal_period_days
    return (
        f"Запуск одного бота — {launch} (единоразово).",
        f"Работа запущенного бота — {', '.join(periodic)} за {days} дней." if periodic else "",
    )


def _page(title: str, body: str) -> Response:
    """Один документ. Без сборки фронтенда: эти страницы должны открываться
    у юриста, у эквайера и у поддержки Telegram — то есть всегда, даже если
    приложение не поднялось."""
    settings = get_settings()
    support = settings.support_contact
    contacts = [f'<a href="https://t.me/{html.escape(support)}">@{html.escape(support)}</a>'] if support else []
    if settings.support_email:
        email = html.escape(settings.support_email)
        contacts.append(f'<a href="mailto:{email}">{email}</a>')

    return Response(
        content=f"""<!doctype html>
<html lang="ru">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(title)}</title>
<style>
  :root {{ color-scheme: light dark; }}
  body {{
    margin: 0 auto; padding: 32px 20px 80px; max-width: 760px;
    font: 16px/1.65 -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
  }}
  h1 {{ font-size: 25px; line-height: 1.25; }}
  h2 {{ margin-top: 34px; font-size: 18px; }}
  li {{ margin-bottom: 6px; }}
  .meta {{ opacity: 0.65; font-size: 14px; }}
  .req {{ margin-top: 40px; padding: 16px; border-radius: 10px; background: rgba(127,127,127,0.12); font-size: 14px; }}
  a {{ color: inherit; }}
</style>
</head>
<body>
<h1>{html.escape(title)}</h1>
<p class="meta">Редакция от {date.today().strftime("%d.%m.%Y")}</p>
{body}
<div class="req">
  <p><strong>{html.escape(settings.legal_name)}</strong><br>
  {html.escape(settings.legal_id)}{"<br>" + html.escape(settings.legal_address) if settings.legal_address else ""}</p>
  <p>Связаться: {" · ".join(contacts) if contacts else "—"}</p>
</div>
</body>
</html>
""",
        media_type="text/html; charset=utf-8",
    )


def _require_requisites() -> None:
    if not get_settings().legal_ready:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Not found")


@router.get("/offer", response_class=Response)
async def offer() -> Response:
    _require_requisites()
    settings = get_settings()
    launch, periodic = _prices()
    site = html.escape(settings.public_base_url.rstrip("/"))
    name = html.escape(settings.legal_name)
    grace = settings.renewal_grace_days

    return _page(
        "Публичная оферта",
        f"""
<p>{name} (далее — «Исполнитель») предлагает любому дееспособному лицу
(далее — «Пользователь») заключить договор на использование сервиса
конструктора Telegram-ботов, размещённого по адресу {site}, на условиях,
изложенных ниже.</p>

<h2>1. Предмет</h2>
<ul>
  <li>Исполнитель предоставляет доступ к сервису, позволяющему собрать
      сценарий Telegram-бота и запустить его в работу на серверах Исполнителя.</li>
  <li>Регистрация, сборка сценария, его хранение, редактирование и
      предварительный просмотр предоставляются бесплатно и без ограничения срока.</li>
  <li>Платным является запуск бота в Telegram и его дальнейшая работа.</li>
</ul>

<h2>2. Стоимость и порядок оплаты</h2>
<ul>
  <li>{html.escape(launch)}</li>
  {f"<li>{html.escape(periodic)}</li>" if periodic else ""}
  <li>Стоимость показывается Пользователю до списания — на экране публикации бота.</li>
  <li>Оплата производится через платёжные сервисы, указанные на странице оплаты.
      Исполнитель не хранит данные банковских карт Пользователя.</li>
  <li>Если период работы бота не оплачен, бот продолжает работать ещё
      {grace} дней, после чего снимается с публикации. Сценарий, настройки и
      данные при этом сохраняются и остаются доступны Пользователю.</li>
</ul>

<h2>3. Деньги покупателей Пользователя</h2>
<ul>
  <li>Платежи, которые бот Пользователя принимает от его покупателей, поступают
      напрямую на счёт Пользователя в его собственной платёжной системе.
      Исполнитель стороной этих расчётов не является, денежные средства
      покупателей не принимает и не хранит.</li>
  <li>Ключи доступа к платёжной системе Пользователя хранятся в зашифрованном
      виде и используются исключительно для выставления счетов ботом Пользователя.</li>
  <li>Ответственность за товар, услугу и её доставку покупателю, за возвраты,
      за уплату налогов и за соблюдение законодательства о защите прав
      потребителей несёт Пользователь.</li>
</ul>

<h2>4. Что Пользователю запрещено продавать через сервис</h2>
<ul>
  <li>товары и услуги, оборот которых ограничен или запрещён законом;</li>
  <li>материалы, нарушающие права третьих лиц, в том числе авторские;</li>
  <li>рассылки лицам, которые на них не подписывались.</li>
</ul>
<p>При нарушении Исполнитель вправе снять бота с публикации, уведомив
Пользователя.</p>

<h2>5. Возврат</h2>
<ul>
  <li>Если сервис по вине Исполнителя не обеспечил работу бота в течение
      оплаченного периода, оплата за неотработанный период возвращается по
      требованию Пользователя.</li>
  <li>Запрос на возврат направляется по контактам, указанным ниже, и
      рассматривается в течение 10 рабочих дней.</li>
</ul>

<h2>6. Ограничение ответственности</h2>
<ul>
  <li>Сервис предоставляется «как есть». Исполнитель не гарантирует, что бот
      Пользователя принесёт определённый доход.</li>
  <li>Исполнитель не отвечает за перебои в работе Telegram, платёжных систем
      и иных сторонних сервисов, а также за содержание бота Пользователя.</li>
  <li>Ответственность Исполнителя ограничена суммой, уплаченной Пользователем
      за текущий период работы бота.</li>
</ul>

<h2>7. Акцепт и изменения</h2>
<ul>
  <li>Договор считается заключённым с момента регистрации Пользователя в сервисе.</li>
  <li>Исполнитель вправе изменять условия, публикуя новую редакцию по этому
      адресу. Изменения не распространяются на уже оплаченный период.</li>
</ul>
""",
    )


@router.get("/privacy", response_class=Response)
async def privacy() -> Response:
    _require_requisites()
    settings = get_settings()
    name = html.escape(settings.legal_name)

    return _page(
        "Политика конфиденциальности",
        f"""
<p>Настоящая политика описывает, какие данные собирает {name} при
использовании сервиса, зачем и как долго они хранятся.</p>

<h2>1. Данные Пользователя сервиса</h2>
<ul>
  <li>При входе через Telegram сервис получает от Telegram идентификатор,
      имя и, если оно открыто, имя пользователя. Пароль сервис не запрашивает
      и не хранит.</li>
  <li>Сценарии ботов, настройки и загруженные файлы хранятся, пока
      Пользователь не удалит их или свой аккаунт.</li>
  <li>Ключи доступа к платёжной системе Пользователя хранятся в зашифрованном
      виде и не показываются повторно после сохранения.</li>
</ul>

<h2>2. Данные покупателей бота</h2>
<ul>
  <li>Сервис сохраняет идентификатор, имя пользователя Telegram и историю
      заказов тех, кто общался с ботом, — чтобы бот мог выдать оплаченное,
      а владелец бота видел свои продажи.</li>
  <li>Данные банковских карт покупателей сервис не получает и не хранит:
      оплата проходит на стороне платёжной системы.</li>
  <li>Владелец бота является оператором данных своих покупателей; сервис
      обрабатывает эти данные по его поручению и для работы бота.</li>
</ul>

<h2>3. Передача третьим лицам</h2>
<ul>
  <li>Данные передаются только тем сервисам, без которых бот не работает:
      Telegram и выбранной Пользователем платёжной системе.</li>
  <li>Данные не продаются и не передаются в рекламных целях.</li>
</ul>

<h2>4. Хранение и защита</h2>
<ul>
  <li>Данные хранятся на серверах, доступ к которым имеет только Исполнитель.</li>
  <li>Платёжные ключи и токены ботов хранятся в зашифрованном виде.</li>
  <li>Резервные копии создаются регулярно и хранятся в зашифрованном виде.</li>
</ul>

<h2>5. Удаление</h2>
<ul>
  <li>Пользователь может удалить бота вместе со сценарием и файлами в любой
      момент из личного кабинета.</li>
  <li>Запрос на удаление аккаунта и всех связанных данных направляется по
      контактам ниже и исполняется в течение 30 дней.</li>
  <li>Покупатель бота может отказаться от рассылок командой /stop, а от
      подписки — командой /cancel в самом боте.</li>
</ul>
""",
    )
